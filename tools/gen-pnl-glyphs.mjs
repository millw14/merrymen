/**
 * Bake the P&L card's glyph outlines into a source file.
 *
 * WHY THIS EXISTS AT ALL — the card cannot rely on a font at render time.
 *
 * The card is composited by sharp, whose SVG renderer resolves `font-family`
 * through the SYSTEM font stack. Measured on this repo: every family name
 * ("monospace", "DejaVu Sans Mono", "Geist Mono", "sans-serif") produced a
 * byte-identical raster, i.e. they all silently fell back to one face — and an
 * `@font-face` with a base64 `src:` was ignored just as silently. A container
 * with no fonts installed would therefore render a card with no numbers on it
 * and report success. That is not an acceptable failure mode for something the
 * owner is sent as the record of a closed trade.
 *
 * So the text is emitted as PATHS. Paths need no font, no fontconfig and no
 * container packages, and render identically on Windows, CI and Railway.
 *
 * WHY BAKED RATHER THAN CONVERTED AT RUNTIME: converting text to paths needs a
 * TTF parser, and adding one to a worker that moves real money buys a
 * dependency and a supply-chain surface for a cosmetic image. The charset is
 * fixed and small, so the conversion runs ONCE, here, and the worker ships with
 * outlines and no parser.
 *
 * THE FACES mirror the site's own stack — `--sans: "Geist Numerals", "DM Sans"`
 * (web/src/terminal/terminal.css) — so the card's numbers are the site's
 * numbers. Geist Pixel, which is what the template's baked labels are set in,
 * was tried first and rejected on evidence: its glyphs are 1232-3080 path
 * commands each (DM Sans: 8-73), a single headline exceeded 220kB of path data,
 * and past roughly 100kB librsvg silently drops the rest of an attribute — so
 * "+247.8%" rendered as "+24". Digits that vanish from a P&L card are worse
 * than a font that does not match, and 50x the bytes bought that.
 *
 * Run with opentype.js installed but NOT saved, so it never becomes a
 * dependency of the app:
 *
 *   npm install opentype.js --no-save
 *   node tools/gen-pnl-glyphs.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FONTS = path.join(ROOT, "android-native/app/src/main/res/font");
const OUT = path.join(ROOT, "worker/src/pnl-glyphs.ts");

/**
 * Everything a card can print: the numbers, the separators a formatted amount
 * uses, and latin for the token symbol and agent name. A character outside this
 * set is dropped at layout time rather than rendered as a blank box.
 */
const CHARSET =
  "0123456789" +
  "+-.,%$:/()[]#@&'\"!?*= " +
  "ABCDEFGHIJKLMNOPQRSTUVWXYZ" +
  "abcdefghijklmnopqrstuvwxyz" +
  "×→–—•";

const numerals = opentype.parse(readFileSync(path.join(FONTS, "geist_numerals.ttf")));
const sans = opentype.parse(readFileSync(path.join(FONTS, "dm_sans.ttf")));

/** Digits from the numerals face, everything else from DM Sans — the CSS stack. */
const faceFor = (ch) => (ch >= "0" && ch <= "9" ? numerals : sans);

const EM = 1000;
const glyphs = {};
const skipped = [];

for (const ch of CHARSET) {
  const font = faceFor(ch);
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) {
    skipped.push(ch);
    continue;
  }
  // Baked at em scale with the baseline at y=0, already flipped to SVG's
  // y-down space by opentype. A caller scales by size/EM and translates.
  const d = glyph.getPath(0, 0, EM).toPathData(2);
  if (/NaN|Infinity/.test(d)) {
    skipped.push(ch);
    continue;
  }
  const advance = (glyph.advanceWidth * EM) / font.unitsPerEm;
  glyphs[ch] = { d, a: Math.round(advance * 100) / 100 };
}

if (skipped.length) console.warn("skipped (absent or unrenderable):", JSON.stringify(skipped.join("")));

const entries = Object.entries(glyphs)
  .map(([ch, g]) => `  ${JSON.stringify(ch)}: { a: ${g.a}, d: ${JSON.stringify(g.d)} },`)
  .join("\n");

const file = `// GENERATED by tools/gen-pnl-glyphs.mjs — do not edit by hand.
//
// Glyph outlines for the P&L card, baked at em scale so rendering never depends
// on a font being installed where the card is drawn. See the generator for why
// this is paths and not text, and why these two faces.
//
// \`d\` is SVG path data with the baseline at y=0 and the pen starting at x=0,
// in a ${EM}-unit em square. \`a\` is the advance width in the same units.

/** The em square these outlines are drawn in. */
export const PNL_GLYPH_EM = ${EM};

export interface PnlGlyph {
  /** Advance width, in em units. */
  a: number;
  /** SVG path data, baseline at y=0. */
  d: string;
}

export const PNL_GLYPHS: Readonly<Record<string, PnlGlyph>> = Object.freeze({
${entries}
});
`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT}: ${Object.keys(glyphs).length} glyphs, ${(file.length / 1024).toFixed(1)}kB`);
