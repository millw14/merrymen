test("the schema is idempotent and memoised per Db", async (t) => {
  const { db } = await open(t);
  assert.equal(ensureXpostSchema(db, "sqlite"), ensureXpostSchema(db, "sqlite"));
  await db.exec(XPOST_SCHEMA);
});

test("the DDL translates to Postgres cleanly", () => {
  const pg = translateSchema(XPOST_SCHEMA);
  assert.match(pg, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.doesNotMatch(pg, /\bINTEGER\b/);
  assert.doesNotMatch(pg, /AUTOINCREMENT/);
  // translateSchema rewrites blind and `exec` never renumbers: no quote or
  // placeholder may hide in a comment, and no placeholder anywhere.
  const comments = [...XPOST_SCHEMA.matchAll(/--[^\n]*/g)].map((m) => m[0]).join("\n");
  assert.doesNotMatch(comments, /['?]/);
  assert.doesNotMatch(XPOST_SCHEMA, /\?/);
});

// ── pending connects ────────────────────────────────────────────────────────

test("a pending connect is single use, expires, and stores neither the state nor the verifier in the clear", async (t) => {
  const { db, raw } = await open(t);
  await putPending(db, DEK, { state: "w.state-one", tenant: OWNER_A, verifier: "verifier-plain-text", redirectUri: "https://app.test/connect/x", expiresAtMs: 2_000 });
  const stored = JSON.stringify(raw.prepare("SELECT * FROM xpost_pending").all());
  assert.ok(!stored.includes("w.state-one"), "the state is stored hashed");
  assert.ok(!stored.includes("verifier-plain-text"), "the verifier is sealed");

  const first = await takePending(db, DEK, "w.state-one", 1_000);
  assert.deepEqual(first, { tenant: OWNER_A.toLowerCase(), verifier: "verifier-plain-text", redirectUri: "https://app.test/connect/x" });
  assert.equal(await takePending(db, DEK, "w.state-one", 1_000), null, "spent");

  await putPending(db, DEK, { state: "w.state-two", tenant: OWNER_A, verifier: "v2", redirectUri: "https://app.test/connect/x", expiresAtMs: 2_000 });
  assert.equal(await takePending(db, DEK, "w.state-two", 2_000), null, "expired at its expiry");
  assert.equal(await takePending(db, DEK, "w.state-two", 1_000), null, "and deleted, not kept for later");

  await putPending(db, DEK, { state: "w.old", tenant: OWNER_A, verifier: "v", redirectUri: "https://app.test/connect/x", expiresAtMs: 100 });
  assert.equal(await prunePending(db, 1_000), 1);
});

