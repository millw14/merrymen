const OWNER_A = `0x${"AA".repeat(20)}`;
const OWNER_B = `0x${"bb".repeat(20)}`;
const DEK = randomBytes(32);

async function open(t: { after(fn: () => void): void }): Promise<{ db: Db; raw: DatabaseSync }> {
  const raw = new DatabaseSync(":memory:");
  t.after(() => raw.close());
  const db = wrapSqlite(raw);
  await ensureXpostSchema(db, "sqlite");
  return { db, raw };
}

const TOKENS: TokenSetPlain = {
  accessToken: "access-token-secret-1",
  refreshToken: "refresh-token-secret-1",
  accessExpiresAtMs: 10_000,
  scope: "tweet.read tweet.write users.read offline.access",
};

function post(over: Partial<NewPost> = {}): NewPost {
  return {
    tenant: OWNER_A,
    xUserId: "111",
    kind: "casual",
    dedupeKey: `casual:${OWNER_A.toLowerCase()}:2026-09-28`,
    body: "thinking about how quiet markets feel on a sunday",
    dueAtMs: 1_000,
    nowMs: 500,
    ...over,
  };
}

