/**
 * Opt-in real, disposable LOCAL PostgreSQL: the closed-epoch repair through
 * the operator's shell against the production dialect, on 0x0e1ca0's real
 * chain history (testdata/closed-epoch-0e1ca0.json). Never reads DATABASE_URL.
 *
 * What only Postgres can show: a connection opened with
 * default_transaction_read_only that the server holds to; REPEATABLE READ
 * READ ONLY and SERIALIZABLE, each proved by current_setting; grant_json as
 * JSONB read as written (->>); the epoch bounds' millisecond-or-second
 * normalisation as integer division on BIGINT; pg_index read inside the
 * apply's transaction; INSERT … ON CONFLICT DO NOTHING RETURNING against the
 * partial flows_chain_identity; the receipts' partial unique index; the
 * agents row lock (a writer holding it makes the apply wait, then refuse,
 * writing nothing); and the revert's explicit-id re-insert into flows.id,
 * BIGINT GENERATED BY DEFAULT AS IDENTITY.
 *
 * Each run creates its own database and drops it. Run with
 * MERRYMEN_TEST_PG_URL=postgres://…@127.0.0.1:<port>/<db> and the `pg`
 * driver resolvable (NODE_PATH works: it is loaded with require here).
 */
